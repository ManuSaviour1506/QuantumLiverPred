"""File storage for uploads and generated artifacts: local disk (default) or S3-compatible object storage.

Keys are generated by the server (`uploads/<user id>/<uuid>.<ext>`); user-supplied file names are never used to build
paths, and every key is checked so that it cannot escape the storage root (no `..`, no absolute paths).
"""
from __future__ import annotations

import re
import shutil
import tempfile
from pathlib import Path

_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.\-/]{0,300}$")


class StorageError(RuntimeError):
    pass


def check_key(key: str) -> str:
    if not _KEY.match(key) or ".." in key.split("/") or "//" in key or key.endswith("/"):
        raise StorageError("invalid storage key")
    return key


class LocalStorage:
    kind = "local"

    def __init__(self, root: Path):
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def path(self, key: str) -> Path:
        p = (self.root / check_key(key)).resolve()
        if self.root not in p.parents:
            raise StorageError("storage key escapes the storage root")
        return p

    def put_file(self, key: str, src: Path) -> None:
        dst = self.path(key)
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)

    def put_bytes(self, key: str, data: bytes) -> None:
        dst = self.path(key)
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(data)

    def get_bytes(self, key: str) -> bytes:
        return self.path(key).read_bytes()

    def local_copy(self, key: str) -> Path:
        return self.path(key)

    def exists(self, key: str) -> bool:
        return self.path(key).exists()

    def delete(self, key: str) -> None:
        p = self.path(key)
        if p.is_dir():
            shutil.rmtree(p, ignore_errors=True)
        else:
            p.unlink(missing_ok=True)

    def delete_prefix(self, prefix: str) -> None:
        p = self.path(prefix.rstrip("/"))
        if p.is_dir():
            shutil.rmtree(p, ignore_errors=True)

    def describe(self) -> dict:
        return {"backend": "local", "persistent": "only if this directory is on a persistent volume"}


class S3Storage:
    """S3-compatible storage through boto3 (optional dependency). Not exercised in the offline build environment."""
    kind = "s3"

    def __init__(self, bucket: str, prefix: str = "", endpoint_url: str = "", region: str = ""):
        try:
            import boto3  # type: ignore
        except ImportError as e:
            raise StorageError("STORAGE_BACKEND=s3 needs boto3 (pip install boto3)") from e
        self.bucket, self.prefix = bucket, prefix
        self.client = boto3.client("s3", endpoint_url=endpoint_url or None, region_name=region or None)
        self._tmp = Path(tempfile.mkdtemp(prefix="lti_s3_"))

    def _k(self, key: str) -> str:
        return self.prefix + check_key(key)

    def put_file(self, key: str, src: Path) -> None:
        self.client.upload_file(str(src), self.bucket, self._k(key))

    def put_bytes(self, key: str, data: bytes) -> None:
        self.client.put_object(Bucket=self.bucket, Key=self._k(key), Body=data)

    def get_bytes(self, key: str) -> bytes:
        return self.client.get_object(Bucket=self.bucket, Key=self._k(key))["Body"].read()

    def local_copy(self, key: str) -> Path:
        dst = self._tmp / check_key(key)
        dst.parent.mkdir(parents=True, exist_ok=True)
        self.client.download_file(self.bucket, self._k(key), str(dst))
        return dst

    def exists(self, key: str) -> bool:
        try:
            self.client.head_object(Bucket=self.bucket, Key=self._k(key))
            return True
        except Exception:
            return False

    def delete(self, key: str) -> None:
        self.client.delete_object(Bucket=self.bucket, Key=self._k(key))

    def delete_prefix(self, prefix: str) -> None:
        paginator = self.client.get_paginator("list_objects_v2")
        for page in paginator.paginate(Bucket=self.bucket, Prefix=self._k(prefix.rstrip("/")) + "/"):
            for obj in page.get("Contents", []):
                self.client.delete_object(Bucket=self.bucket, Key=obj["Key"])

    def describe(self) -> dict:
        return {"backend": "s3", "bucket": self.bucket, "persistent": True}


def make_storage(settings):
    if settings.storage_backend == "s3":
        return S3Storage(settings.s3_bucket, settings.s3_prefix, settings.s3_endpoint_url, settings.s3_region)
    return LocalStorage(settings.storage_dir)
