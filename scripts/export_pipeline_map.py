"""Write docs/MODEL_PIPELINE_MAP.md: every registered model -> comparison family, execution pipeline, inputs, features,
runtime availability and the reason when it cannot run (generated from the live registry, not written by hand).

    python scripts/export_pipeline_map.py
"""
from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

FAM = {"classical": "Classical ML", "deep_learning": "Deep Learning", "quantum": "Quantum ML", "hybrid": "Hybrid ML"}


def pipeline(eng, d: dict) -> str:
    mid = d["id"]
    if d.get("source") == "v10":
        card = eng.entries[mid].model.card if eng.entries[mid].model is not None else {}
        kind = card.get("kind", "")
        return {"v10_patch_sklearn": "radiomics features -> scikit-learn pipeline -> Platt",
                "v10_patch_vqc": "radiomics -> fold PCA angles -> VQC (CPU state-vector simulation) -> Platt",
                "v10_patch_qksvm": "radiomics -> fold PCA angles -> fidelity quantum kernel SVM (simulated) -> Platt",
                "v10_patch_hybrid": "radiomics -> classical MLP + VQC head / ablation (simulated) -> Platt",
                "v10_patch_late_fusion": "radiomics -> LR + VQC standardised-logit average -> Platt"}.get(kind, kind)
    lm = eng.v9.models.get(mid) if eng.v9 else None
    if lm is None:
        return "—"
    k, meta = lm.kind, lm.meta
    if k == "numpy_cnn":
        n = {0: "2-D (1 slice)", 1: "2.5-D (3 slices)", 2: "5-slice / 3-D"}[lm.context_slices]
        return f"64-px patch stack -> NumPy CNN {n} -> V9 Platt calibration"
    if k == "cnn_finetune":
        return f"frozen ImageNet {meta.get('arch')} trunk -> fine-tuned tail -> V9 Platt"
    if k == "radiomics_v9":
        return "normalised patch -> radiomics (GLCM / LBP / intensity) -> classical model -> V9 Platt"
    if str(k).startswith("v9_"):
        src = "V9 2.5-D CNN embedding" if meta.get("features") == "cnn25d_v9" else "fine-tuned EfficientNet-B0 GAP"
        head = {"v9_vqc": "VQC (simulated)", "v9_qksvm": "quantum kernel SVM (simulated)", "v9_hybrid": "hybrid CNN + VQC (simulated)",
                "v9_twin": "classical twin MLP", "v9_lr_control": "PCA -> logistic regression (control)",
                "v9_rbf_control": "PCA -> RBF SVM (control)"}.get(k, k)
        return f"{src} -> {head} -> V9 Platt"
    return str(k)


def main() -> int:
    from src.v10.engine.registry import ModelEngine
    eng = ModelEngine(ROOT).load()
    groups: dict[str, list] = defaultdict(list)
    for d in eng.list(include_legacy=True):
        if d.get("family") == "segmentation":
            continue
        groups[d.get("compare_family") or "classical"].append(d)
    L = ["# Model -> execution pipeline map", "",
         "Generated by `scripts/export_pipeline_map.py` from the live registry. Every model shares the same front end "
         "(decode -> QC -> OOD -> 96-px patch grid -> liver gate -> U-Net liver validation) before its own pipeline.", "",
         "| Availability | Count |", "|---|---:|"]
    from collections import Counter
    for k, v in sorted(Counter(d.get("availability") for ds in groups.values() for d in ds).items()):
        L.append(f"| {k} | {v} |")
    for fam in ("classical", "deep_learning", "quantum", "hybrid"):
        L += ["", f"## {FAM[fam]}", "", "| Model | Source | Architecture | Pipeline | Context | Availability | Reason |",
              "|---|---|---|---|---|---|---|"]
        for d in sorted(groups.get(fam, []), key=lambda d: (not d.get("servable"), d["id"])):
            ctx = d.get("context_slices_each_side") or 0
            L.append(f"| `{d['id']}` | {d.get('source')} {d.get('version')} | {d.get('architecture') or ''} | {pipeline(eng, d)} | "
                     f"{'single slice' if not ctx else f'{2 * ctx + 1} slices'} | {d.get('availability')} | "
                     f"{(d.get('reason') or '').replace('|', '/')[:160]} |")
    out = ROOT / "docs" / "MODEL_PIPELINE_MAP.md"
    out.write_text("\n".join(L) + "\n")
    print(f"wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
