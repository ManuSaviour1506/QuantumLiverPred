#!/usr/bin/env python3
"""Write the SYNTHETIC software-test fixtures (abstract phantoms, not medical images):
dataset/sample_data/synthetic/{images/*.png, manifest.csv, synthetic_phantoms.zip}.

    python scripts/v10_make_synthetic_fixtures.py [--with-model ARTIFACTS_V10_DIR]
--with-model also trains the software-test model there (served only with ALLOW_SYNTHETIC_MODELS=true).
"""
import argparse
import csv
from pathlib import Path

from _common import ROOT

if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--with-model", default=None)
    a = ap.parse_args()
    from src.v10.data.synthetic import dataset_zip, make_dataset, train_synthetic_model
    out = ROOT / "dataset" / "sample_data" / "synthetic"
    entries = make_dataset(12, 4)
    for name, data, _ in entries:
        (out / name).parent.mkdir(parents=True, exist_ok=True)
        (out / name).write_bytes(data)
    with open(out / "manifest.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(entries[0][2]))
        w.writeheader()
        w.writerows(e[2] for e in entries)
    (out / "synthetic_phantoms.zip").write_bytes(dataset_zip(entries))
    (out / "README.md").write_text("SYNTHETIC software-test fixtures: abstract phantoms generated by "
                                   "src/v10/data/synthetic.py. Not medical images; never use them as data.\n")
    print(f"wrote {len(entries)} phantoms to {out}")
    if a.with_model:
        print("model:", train_synthetic_model(Path(a.with_model)))
